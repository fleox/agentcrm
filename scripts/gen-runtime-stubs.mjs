#!/usr/bin/env node
// Regenerates the third-party runtime stubs of public/runtime/ (react,
// react/jsx-runtime, react-dom, react-dom/client, react-i18next,
// lucide-react) from the export names of the installed packages. Run it
// after upgrading one of them (src/extensions/runtime.test.ts fails until
// you do). public/runtime/agentcrm-runtime.js is hand-written.
//
//   node scripts/gen-runtime-stubs.mjs

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(root, "public/runtime");

const STUBS = [
  { spec: "react", file: "react.js", hasDefault: true },
  { spec: "react/jsx-runtime", file: "react-jsx-runtime.js" },
  { spec: "react-dom", file: "react-dom.js", hasDefault: true },
  { spec: "react-dom/client", file: "react-dom-client.js" },
  { spec: "react-i18next", file: "react-i18next.js" },
  { spec: "lucide-react", file: "lucide-react.js", hasDefault: false, lazy: true },
];

const IDENT = /^[A-Za-z_$][\w$]*$/;

export async function stubSource({ spec, hasDefault, lazy }) {
  const mod = await import(spec);
  const names = Object.keys(mod)
    .filter((k) => k !== "default" && IDENT.test(k))
    .sort();
  const header = [
    `// Runtime stub for "${spec}" — GENERATED by scripts/gen-runtime-stubs.mjs, do not edit.`,
    "// The import map of the admin's index.html (and the extension loader's",
    "// specifier rewrite) points external bundles here; it re-exports the",
    "// admin's own instance from globalThis.__AGENTCRM_RUNTIME__ so there is",
    "// only one copy in the page.",
    lazy ? "// Loaded on demand: the loader prepares it before importing a bundle that uses it." : "",
    "",
    "const G = globalThis.__AGENTCRM_RUNTIME__;",
    `const M = G && G.modules ? G.modules[${JSON.stringify(spec)}] : null;`,
    "if (!M) {",
    "  throw new Error(",
    `    "[agentcrm] ${spec} is not available: globalThis.__AGENTCRM_RUNTIME__ is not initialised (src/extensions/runtime.ts must be imported first).",`,
    "  );",
    "}",
    "",
  ].filter((l, i) => l !== "" || i > 5);
  const body = [];
  if (hasDefault) body.push("export default M.default ?? M;");
  // One destructuring export, wrapped for readability.
  const lines = [];
  let line = "";
  for (const n of names) {
    if ((line + n).length > 110) {
      lines.push(line);
      line = "";
    }
    line += `${n}, `;
  }
  if (line) lines.push(line);
  body.push(`export const {\n${lines.map((l) => `  ${l.trim()}`).join("\n")}\n} = M;`);
  return `${header.join("\n")}\n${body.join("\n")}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  for (const s of STUBS) {
    writeFileSync(resolve(out, s.file), await stubSource(s));
    console.log(`public/runtime/${s.file}`);
  }
}

export { STUBS };
